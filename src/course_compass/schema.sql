-- Screenshots of official grade statistics uploaded by students. Someone (or a
-- later OCR step) reads the counts and adds them to the grade tables, then
-- sets the status to 'accepted' or 'rejected'.
CREATE TABLE IF NOT EXISTS grade_distribution_uploads (
    upload_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL REFERENCES courses(course_id) ON DELETE CASCADE,
    semester TEXT NOT NULL,
    exam_type TEXT NOT NULL CHECK (exam_type IN ('endterm', 'retake')),
    file_name TEXT,
    content_type TEXT NOT NULL,
    image BYTEA NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'accepted', 'rejected')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
